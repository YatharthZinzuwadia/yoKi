import { chromium } from 'playwright'
import { execFileSync } from 'node:child_process'
const browser = await chromium.launch({ args: ['--enable-gpu', '--ignore-gpu-blocklist', '--use-gl=angle', '--use-angle=gl'], env: { ...process.env, __NV_PRIME_RENDER_OFFLOAD: '1', __GLX_VENDOR_LIBRARY_NAME: 'nvidia' } })
const page = await browser.newPage({ viewport: { width: 480, height: 270 } })
await page.goto('http://localhost:5173/?debug')
await page.waitForFunction(() => window.__yoki?.ui.getState().ready, null, { timeout: 120000 })
await page.waitForTimeout(2500)
await page.mouse.click(240, 135)
await page.waitForTimeout(1200)
const mean = async () => { await page.waitForTimeout(300); const b = await page.screenshot(); return Number(execFileSync('magick', ['png:-', '-format', '%[fx:mean]', 'info:'], { input: b }).toString()).toFixed(4) }
await page.evaluate(() => window.__yoki.seek(18.7))
console.log('base', await mean())
console.log(await page.evaluate(() => { const P = window.__post; const u = (e) => Object.fromEntries([...e.uniforms].map(([k, v]) => [k, typeof v.value === 'number' ? v.value : String(v.value?.constructor?.name)])); return JSON.stringify({ paint: u(P.paint), bloom: P.bloom.intensity, ink: u(P.ink) }) }))
await page.evaluate(() => { window.__post.composer.multisampling = 0 })
console.log('msaa 0', await mean())
await page.evaluate(() => { window.__post.composer.multisampling = 4 })
await page.evaluate(() => { const ep = window.__post.composer.passes[2]; window.__savedEffects = ep.effects; ep.setEffects([window.__post.paint]) })
console.log('paint only', await mean())
await page.evaluate(() => { const ep = window.__post.composer.passes[2]; ep.setEffects([window.__post.bloom]) })
console.log('bloom only', await mean())
await browser.close()
